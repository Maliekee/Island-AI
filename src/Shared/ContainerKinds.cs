// Shared SOURCE, linked into Island UI and Island Ex (see PatchCensus.cs): what
// a container IS, as far as the game's machinery goes. Island UI's
// ContainerPolicy builds its pool, its families and its safety gates on this;
// Island Ex's chest crafting asks it which containers are plain storage.
namespace Shared
{
    internal static class ContainerKinds
    {
        internal enum Engine
        {
            // The slots ARE the state. Nothing watches them, so a write from
            // anywhere is complete the moment it lands.
            Inert,
            // `InventoryManager.BreedInventory()` polls the MIRROR slots while the
            // vanilla panel is open and calls TrapLoad / PetCheck / PlanterCheck /
            // FarmCheck for each slot that changed. Those calls are the half that
            // puts the NPC in the cage, plants the seed, sets the bait.
            Breed,
            // `InventoryManager.RackInventory()` does the same for fourteen prop
            // types, dispatching to a *Check per type (InventoryManager.cs:994).
            Rack,
            // Vanilla moves a bench's strip into the mirror and CONSUMES from
            // there. Safe only while the bench redirect keeps craftPanelID at 0.
            Bench,
            // Loot generated by TreasureScript.TreasureSet on first open.
            Treasure,
            // The panel is a launcher: the slots hold state but the interaction
            // runs a coroutine or raises a prop panel.
            Prop,
        }

        // BreedInventory's switch verbatim (InventoryManager.cs:889). The SEVEN,
        // not "anything carrying a BreedInfo" — widening this has already been
        // paid for once, and the census shows why the narrow list is right: the
        // harvest box and the mine both carry a BreedInfo (Harvest, Stone) that
        // no poll anywhere reads, so both are plain storage and always were.
        internal static bool PolledBreed(BreedInfo.BreedType t)
        {
            switch (t)
            {
                case BreedInfo.BreedType.Trap:
                case BreedInfo.BreedType.Planter:
                case BreedInfo.BreedType.Pet:
                case BreedInfo.BreedType.Egg:
                case BreedInfo.BreedType.Mushroom:
                case BreedInfo.BreedType.Beehive:
                case BreedInfo.BreedType.Herb:
                    return true;
            }
            return false;
        }

        // RackInventory's dispatch list (InventoryManager.cs:994), plus Rack
        // itself: Rack is in the LOAD switch that starts the coroutine, and
        // starting it is what makes the mirror load-bearing.
        internal static bool PolledRack(InventorySlot.Type t)
        {
            switch (t)
            {
                case InventorySlot.Type.Rack:
                case InventorySlot.Type.Pole:
                case InventorySlot.Type.Toilet:
                case InventorySlot.Type.Dye:
                case InventorySlot.Type.Restrain:
                case InventorySlot.Type.GlassTank:
                case InventorySlot.Type.BodyRack:
                case InventorySlot.Type.ShowCase:
                case InventorySlot.Type.Table:
                case InventorySlot.Type.Capsule:
                case InventorySlot.Type.Milk:
                case InventorySlot.Type.ItemStand:
                case InventorySlot.Type.Picture:
                case InventorySlot.Type.Core:
                    return true;
            }
            return false;
        }

        // Vanilla's own list of the Type.Edit props that carry storage
        // (UIManager.cs:2131): the two closets, named by key because the type is
        // shared with the mirror and the surgery bed, which hold nothing. Their
        // dress-up runs off the prop panel and never reads these slots.
        internal static bool IsCloset(InventorySlot c)
        {
            if (c == null || c.type != InventorySlot.Type.Edit)
            {
                return false;
            }
            var info = c.GetComponent<ItemInfo>();
            return info != null
                && (info.itemKey == "closet_spider" || info.itemKey == "closet_pretty");
        }

        internal static Engine EngineOf(InventorySlot container)
        {
            if (container == null)
            {
                return Engine.Inert;
            }
            // Order matters: a breed prop is Type.None, so the type test below
            // would call it inert. The component is the more specific fact.
            var breed = container.GetComponent<BreedInfo>();
            if (breed != null && PolledBreed(breed.breedType))
            {
                return Engine.Breed;
            }
            if (PolledRack(container.type))
            {
                return Engine.Rack;
            }
            switch (container.type)
            {
                case InventorySlot.Type.Bench:
                    return Engine.Bench;
                case InventorySlot.Type.Treasure:
                    return Engine.Treasure;
                case InventorySlot.Type.None:
                case InventorySlot.Type.Material:
                // the collector's act only adds flesh through ItemToChest; its
                // slots are a bag like any chest's
                case InventorySlot.Type.FleshCollector:
                    return Engine.Inert;
                // a closet's twenty slots are as inert as a chest's; the mirror
                // and the surgery bed share the type and stay props
                case InventorySlot.Type.Edit:
                    return IsCloset(container) ? Engine.Inert : Engine.Prop;
            }
            return Engine.Prop;
        }

        // A character's bag is a colliderless child of the character, which is
        // vanilla's own test for it (VanillaContainerUI.IsCharacterBag's shape).
        internal static bool IsCharacterBag(InventorySlot c)
        {
            return c != null && c.transform.parent != null
                && c.transform.parent.GetComponent<CommonStates>() != null;
        }

        // Vanilla's own refusal, verbatim (PlayerMove.UseProp, PlayerMove.cs:793):
        // a prop that carries a DefenceInfo, has a life bar, and has run it out
        // is a wreck. UseProp skips the chest branch for one - no
        // SubInventoryLoad - and the build panel offers Repair alone, so the
        // contents are locked behind the repair. NOT an engine fact: a
        // wrecked chest is as inert as a whole one and a write to it would land,
        // which is exactly why the engine could not have caught it. It is the
        // game's rule about ACCESS, asked before any engine question and by the
        // focus as well as the pool - the two routes we have to what a
        // container holds, and a raid's consequence must hold on both.
        internal static bool IsWrecked(InventorySlot c)
        {
            if (c == null)
            {
                return false;
            }
            var info = c.GetComponent<ItemInfo>();
            if (info == null || info.lifeMax <= 0f || info.life > 0f)
            {
                return false;
            }
            return c.GetComponent<DefenceInfo>() != null;
        }
    }
}
